const POCKETS: [string, string][] = [
  ['superior esquerda', 'top left'],
  ['superior do meio', 'top middle'],
  ['superior direita', 'top right'],
  ['inferior esquerda', 'bottom left'],
  ['inferior do meio', 'bottom middle'],
  ['inferior direita', 'bottom right'],
];
const pocket = (s: string) => POCKETS.reduce((a, [pt, en]) => a.replace(pt, en), s);
const FOULS: [string, string][] = [
  ['a branca não tocou nenhuma bola', 'the cue ball hit no ball'],
  ['com a mesa aberta, a 8 não pode ser a primeira bola tocada', 'with an open table, the 8 cannot be the first ball hit'],
  ['era obrigatório tocar a bola 8 primeiro', 'the 8 had to be hit first'],
  ['tocou primeiro uma bola do adversário', "hit an opponent's ball first"],
  ['bola branca encaçapada', 'cue ball potted'],
  ['nenhuma bola tocou a tabela após o contato', 'no ball touched a cushion after contact'],
  ['abertura ilegal (nenhuma bola encaçapada e menos de 4 bolas na tabela)', 'illegal break (no ball potted and fewer than 4 balls to a cushion)'],
  ['tempo da tacada esgotado', 'shot clock ran out'],
];
const foul = (s: string) => FOULS.reduce((a, [pt, en]) => a.replace(pt, en), s);

